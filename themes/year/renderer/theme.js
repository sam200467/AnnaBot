(function () {
  "use strict";
  const data = ThemeKit.data(), fmt = ThemeKit.format;
  const $ = (id) => document.getElementById(id);
  const el = (tag, cls, text) => { const n = document.createElement(tag); if (cls) n.className = cls; if (text !== undefined) n.textContent = text; return n; };
  // 落雪的曲绘没下到（null）时留一块深色方块，不让整张图出不来
  const jacket = (song) => { const img = el("img"); img.alt = ""; if (song && song.jacket) img.src = song.jacket; return img; };
  const trunc2 = (v) => Math.floor((Number(v) || 0) * 100 + 1e-8) / 100;

  function header() {
    $("year").textContent = data.year;
    $("subtitle").textContent = data.generatedAt ? "落雪生成于 " + data.generatedAt : data.year + " 年的上传记录";
  }

  function overview() {
    const root = $("overview");
    const stat = (label, build, cls) => { const s = el("div", "stat" + (cls ? " " + cls : "")); s.append(el("label", "", label)); const v = el("div", "value"); build(v, s); s.append(v); root.append(s); };
    stat("上传成绩", (v) => v.append(el("strong", "plain", String(data.uploads)), el("span", "unit", "次")));
    stat("上传天数", (v) => {
      v.append(el("strong", "plain", String(data.days)), el("span", "unit", "天"));
      if (data.activeMonths) v.append(el("span", "aside", "分布在 " + data.activeMonths + " 个月"));
    });
    if (data.rating) {
      // Rating 照账号 Rating 的写法截到两位；涨幅用截过的两个数相减，屏幕上的数对得上
      const { start, end } = data.rating;
      const gain = Math.round((trunc2(end) - trunc2(start)) * 100) / 100;
      stat("Rating（年内第一次 → 最后一次上传）", (v) => {
        v.append(el("strong", "tier-" + ThemeKit.ratingTier(start), fmt.rating(start)), el("span", "arrow", "⟶"),
          el("strong", "tier-" + ThemeKit.ratingTier(end), fmt.rating(end)),
          el("span", "gain" + (gain < 0 ? " loss" : ""), (gain < 0 ? "−" : "+") + Math.abs(gain).toFixed(2)));
      }, "rating");
    }
  }

  function top() {
    const podium = $("podium");
    // 领奖台：第一名在中间、最高，第二名在左，第三名在右（照落雪网页）
    for (const rank of [2, 1, 3]) {
      const song = data.top[rank - 1];
      if (!song) continue;
      const place = el("div", "place p" + rank);
      const box = el("div", "jacket-box");
      box.append(jacket(song), el("span", "rank-badge", String(rank)));
      const count = el("div", "count", String(song.count));
      count.append(el("small", "", "次"));
      place.append(box, el("div", "song-title", song.title), count);
      podium.append(place);
    }
    const rest = $("rest");
    for (const song of data.top.slice(3)) {
      const li = el("li");
      li.append(el("span", "no", String(song.rank)), jacket(song), el("span", "song-title", song.title), el("span", "count", String(song.count)));
      rest.append(li);
    }
  }

  function months() {
    const grid = $("months");
    const max = Math.max(1, ...data.months.map((m) => m.count));
    for (const m of data.months) {
      const cell = el("div", "month" + (m.count ? "" : " empty"));
      const head = el("div", "head");
      head.append(el("span", "name", m.month + " 月"), el("span", "n", m.count ? String(m.count) : "—"));
      const jackets = el("div", "jackets");
      for (const song of m.songs) jackets.append(jacket(song));
      cell.append(head, jackets);
      if (m.count) { const bar = el("div", "bar"); bar.style.width = (m.count / max * 100).toFixed(1) + "%"; cell.append(bar); }
      grid.append(cell);
    }
  }

  // 下面一排：2025 年起才有这些分布，没有就整块不画
  function bottom() {
    if (!data.ranks && !data.marks && !data.levels) { $("bottom").remove(); return; }
    const cells = $("cells");
    if (data.ranks || data.marks) {
      for (const r of data.ranks || []) {
        const c = el("div", "cell");
        c.append(el("span", "chip r-" + r.key, r.label), el("b", "", String(r.count)));
        cells.append(c);
      }
      if (data.ranks && data.marks) cells.append(el("div", "divider"));
      for (const m of data.marks || []) {
        const c = el("div", "cell");
        c.append(el("span", "chip " + m.kind, m.label), el("b", "", String(m.count)));
        cells.append(c);
      }
    } else {
      $("marks-panel").remove();
    }
    if (data.levels && data.levels.length) {
      const bars = $("bars");
      const max = Math.max(1, ...data.levels.map((l) => l.count));
      for (const l of data.levels) {
        const col = el("div", "bar-col");
        const b = el("div", "b");
        b.style.height = Math.max(3, l.count / max * 92).toFixed(1) + "px";
        col.append(el("span", "v", String(l.count)), b, el("span", "l", l.level));
        bars.append(col);
      }
    } else {
      $("levels-panel").remove();
    }
  }

  function footer() {
    $("credit").textContent = "Generated by Anna Bot · 数据来自落雪查分器" + (data.example ? " · 示例数据" : "") +
      " · 次数按上传的成绩记录算：同一首歌上传几次就算几次，评级、连击、难度也是";
    // 落雪 2025 年存的快照里没有新曲 N20，Rating 照落雪网页按旧算法算，注明一下
    $("note").textContent = data.rating && data.rating.legacy ? "Rating 按旧算法：B30 + 最高一首 × 10，再 ÷ 40（落雪当时的记录里没有新曲 N20）" : "";
  }

  // ── 名片板：照 /推分记录 ──
  function renderIdentity() {
    const player = data.player || {};
    if (!player.name) { $("identity").remove(); return; }
    const plate = $("plate");
    if (player.plate) {
      const img = $("plate-img");
      img.src = player.plate;
      img.addEventListener("error", () => { img.remove(); plate.classList.add("empty"); }, { once: true });
    } else {
      plate.classList.add("empty");
    }
    const trophy = $("trophy");
    if (player.trophy && player.trophy.name) {
      trophy.classList.add(player.trophy.color || "normal");
      trophy.append(el("span", null, player.trophy.name));
    } else {
      trophy.remove();
    }
    const level = $("level");
    if (player.reborn) level.append(el("span", "star", "★" + player.reborn));
    if (player.level !== null && player.level !== undefined) level.append(el("span", "lv", "Lv."), el("span", null, player.level));
    $("name").textContent = player.name || "";
    const overall = $("rating");
    overall.textContent = fmt.rating(player.rating);
    overall.classList.add("tier-" + ThemeKit.ratingTier(player.rating));
    const medallion = document.querySelector(".medallion");
    if (player.character) {
      const chara = $("chara");
      chara.src = player.character;
      chara.addEventListener("error", () => { chara.remove(); medallion.classList.add("empty"); }, { once: true });
    } else {
      medallion.classList.add("empty");
    }
    const emblem = $("emblem");
    const { base = 0, medal = 0 } = player.classEmblem || {};
    const badge = (kind, n) => {
      const img = el("img", kind);
      img.alt = "";
      img.src = "../../shared/icons/class_emblem/" + kind + "/" + n + ".webp";
      img.addEventListener("error", () => img.remove(), { once: true });
      return img;
    };
    if (base) emblem.append(badge("base", base));
    if (medal) emblem.append(badge("medal", medal));
    if (!base && !medal) emblem.remove();
  }

  function fitPlate() {
    const trophy = document.querySelector(".trophy span");
    if (trophy) {
      const ratio = (trophy.parentElement.clientWidth - 24) / trophy.scrollWidth;
      if (ratio < 1) trophy.style.transform = "scale(" + ratio.toFixed(3) + ")";
    }
    const who = document.querySelector(".plate-name .who");
    if (!who) return;
    const room = who.parentElement.clientWidth - 6;
    if (room > 0 && who.scrollWidth > room) who.style.transform = "scale(" + Math.max(0.3, room / who.scrollWidth).toFixed(3) + ")";
  }

  // 底板的衣料取 TA 的立绘：黑外套一小块做表格底，胭脂红披风一小块做标题条（照 /推分记录 的做法）
  async function textures() {
    const art = $("avenius");
    await art.decode();
    const crop = (sx, sy, sw, sh, w, h) => {
      const c = document.createElement("canvas"); c.width = w; c.height = h;
      c.getContext("2d").drawImage(art, sx, sy, sw, sh, 0, 0, w, h);
      return 'url("' + c.toDataURL() + '")';
    };
    // 外套右片金边和盘扣之间那块纯黑的料子；左片窄、带盘扣，裁到会平铺出一排「∞」
    document.documentElement.style.setProperty("--coat", crop(448, 468, 36, 56, 150, 230));
    document.documentElement.style.setProperty("--cape", crop(150, 650, 80, 60, 200, 140));
  }

  // 曲名一行放不下时先缩字（最小 23px，再小就跟旁边的行差太多），还放不下才省略号：精灵记那种「《自戒》 ～ Paganelope」不缩的话只剩书名号
  function fitTitles() {
    document.querySelectorAll(".song-title").forEach((node) => {
      let size = parseFloat(getComputedStyle(node).fontSize);
      while (node.scrollWidth > node.clientWidth && size > 23) node.style.fontSize = (--size) + "px";
    });
  }

  async function main() {
    header(); overview(); top(); months(); bottom(); footer(); renderIdentity();
    await textures();
    await document.fonts.ready;
    fitPlate();
    fitTitles();
    await ThemeKit.done({ element: $("page") });
  }
  main().catch(ThemeKit.fail);
})();
