(function () {
  "use strict";
  const data = ThemeKit.data(), fmt = ThemeKit.format;
  const $ = (id) => document.getElementById(id);
  const el = (tag, cls, text) => { const n = document.createElement(tag); if(cls)n.className=cls; if(text!==undefined)n.textContent=text; return n; };
  const rt = (v) => Number(v||0).toFixed(3);
  const sr = (v) => Number(v||0).toFixed(4).replace(/0$/, "");
  const sign = (v) => (v < -.0005 ? "−" : "+")+Math.abs(v).toFixed(3);
  const num = (text, cls="") => el("span","num "+cls,text);
  const badge = (row) => el("span","difficulty d"+row.levelIndex,["BAS","ADV","EXP","MAS","ULT"][row.levelIndex]||"—");
  const constant = (row) => num(Number(row.constant)>0?fmt.constant(row.constant):"—","constant");
  function header() {
    $("batch-time").textContent="最新一次更新 · "+data.batchTime;
    $("account-rating").textContent=fmt.rating(data.rating.now);
    $("account-rating").className="tier-"+ThemeKit.ratingTier(data.rating.now);
    $("before").textContent=rt(data.rating.start); $("after").textContent=rt(data.rating.end);
    $("before").className="tier-"+ThemeKit.ratingTier(data.rating.start);
    $("after").className="tier-"+ThemeKit.ratingTier(data.rating.end);
    $("impact").textContent=sign(data.rating.gain);
    $("total").append("更新",el("strong","",data.counts.total),"张谱面");
    $("composition-note").textContent="新进 "+data.counts.entered+" · 提升 "+data.counts.improved+" · 移出 "+data.counts.left;
    $("detail-note").textContent="分数前后变化 / 单曲 Rating";
    $("credit").textContent="Generated by Anna Bot · 数据来自落雪查分器 · "+(data.example?"示例成绩":data.time);
  }
  function changes() {
    if(!data.changes.length) {
      $("unchanged").hidden=false;
      $("outside-summary").append(el("div","","B50 外提升  "+data.counts.outside+" 张"),el("div","","成绩更新见右侧列表"));
    }
    for(const row of data.changes) {
      const root=el("div","change-row"), top=el("div","change-title"), bottom=el("div","change-bottom");
      top.append(badge(row),constant(row),el("span","song-name",row.title));
      bottom.append(el("span",row.change==="leave"?"loss":"gain",(row.isNew?"新曲 B20":"旧曲 B30")+" · "+({enter:"新进",up:"提升",leave:"移出"}[row.change])),num(sr(row.rating),row.change==="leave"?"loss":"gain"));
      root.append(top,bottom); $("changes").append(root);
    }
    $("change-omission").textContent=data.changesOmitted?"另有 "+data.changesOmitted+" 项构成变化未展开":"旧曲 B30 ＋ 新曲 B20";
  }
  function events() {
    for(const row of data.events) {
      const root=el("div","event-row"), top=el("div","event-top"), bottom=el("div","event-bottom");
      top.append(badge(row),constant(row),el("span","song-name",row.title));
      const status=el("span","status",!row.inB50?"B50 外":row.action==="enter"||row.action==="first"?"进入 B50":"B50 内");
      if(row.fc&&row.fc!==row.prevFc)status.append(el("span","mark",ThemeKit.MARKS[row.fc]?.text||row.fc));
      top.append(status);
      bottom.append(num(row.prevScore==null?fmt.score(row.score)+"（首次）":fmt.score(row.prevScore)+" → "+fmt.score(row.score),"score"));
      const rating=el("span","rating","R ");
      rating.append(num(sr(row.rating)));
      if(row.deltaRating!=null&&Math.abs(row.deltaRating)>.00001)rating.append(num("  "+sign(row.deltaRating),row.deltaRating<0?"loss":"gain"));
      bottom.append(rating); root.append(top,bottom); $("events").append(root);
    }
    $("detail-omission").textContent=data.omitted?"显示 "+data.events.length+" / "+data.counts.total+" 张，另 "+data.omitted+" 张省略；按单曲 Rating 降序":"本次记录全部展示 · 账号涨幅按整批计算";
  }
  async function main() {
    header(); changes(); events();
    await Promise.all([document.fonts.load('30px "Anna Hand"'),document.fonts.load('700 29px "Anna Script"')]);
    await document.fonts.ready;
    // 长曲名最多缩到 26px，再按单行省略；固定表格行高不会把画面推成竖版。
    document.querySelectorAll(".event-top .song-name").forEach((n) => {
      let size=30;
      while(n.scrollWidth>n.clientWidth&&size>26)n.style.fontSize=(--size)+"px";
    });
    await ThemeKit.done({ element:$("page") });
  }
  main().catch(ThemeKit.fail);
})();
