"use strict";
// /OP进度：全曲 OVER POWER 按分类、版本、等级拆开看进度，外加底色（金底、蓝底这些）的条件和推荐游玩（OP 还能涨最多）的谱面。
// 主题是 themes/over-power/（蕾娜斯，丘奇《荒野暮色》调紫 + 乌木蓝玻璃箱式框调紫，设计说明见它的 README）。
//
//   /OP进度            只接受无参数
//
// 算法在 src/over-power.cjs（每首歌只算 OP 最高的那张、满 OP 按最高定数）。游戏的分母只算已经解锁的歌，
// 落雪不知道谁解锁了哪些。作者 2026-10-23 定的：一律按全部曲目已解锁算，图上注明可能跟游戏里有出入。
// 要每张谱面的具体分数，所以只收授权绑定（好友码绑定读到的 /scores 没有分数）。
// 主题吃的数据形状见 themes/over-power/examples/preview-data.json；buildData 是纯函数，测试和示例数据都用它。

const { analyze } = require("../over-power.cjs");
const { playerView, stamp } = require("./best.cjs");

// 横版 2700×1780，按 1.5 倍出（跟 /年度总结、/出勤记录 一样），JPEG 质量 76
const RENDER_SCALE = 1.5;
// 等级那栏只列 10～15+（只算紫谱、黑谱，见 over-power.cjs 的 byLevel）：再往下的紫谱很少
const LEVELS = ["15+", "15", "14+", "14", "13+", "13", "12+", "12", "11+", "11", "10+", "10"];
// 推荐游玩两排曲绘各几张（主题里一排正好放下 6 张）
const HEADROOM = 6;
// 底色：落雪的 rating_possession → 图上的叫法。银色那档画出来是浅蓝，国服玩家都叫蓝底（日本也叫「青ポゼ」）
const POSSESSION_NAMES = { normal: "无底色", copper: "铜底", silver: "蓝底", gold: "金底", platina: "铂底", rainbow: "虹底" };
const RANK_LABELS = { s: "S", sp: "S+", ss: "SS", sss: "SSS" };
const NOTE = "按全部曲目都已解锁计算（落雪不知道哪些歌你还没解锁），可能跟游戏里的数值有出入";

const round2 = (value) => Math.round(value * 100) / 100;
const groupView = (group) => ({ percent: group.percent, op: round2(group.op), max: round2(group.max), played: group.played, count: group.count });

// 推荐游玩的一首歌。没打过的画定数最高的那张（满 OP 按它算），gap 是满 OP；
// 打过的画 over-power.cjs 挑出来的那张（打过的谱面里推满能涨最多的），score 是它的真实分数，gap 是推满能涨多少
function songView(entry, catalog) {
  const chart = entry.pick || entry.top;
  return {
    songId: entry.song.id,
    jacketId: catalog.jacketId ? catalog.jacketId(entry.song) : entry.song.id,
    title: entry.song.title,
    levelIndex: chart.chart.difficulty,
    level: chart.chart.level,
    constant: Number(chart.chart.level_value),
    score: entry.pick ? entry.pick.play.score : null,
    op: round2(entry.op),
    max: entry.max,
    gap: round2(entry.pick ? entry.gain : entry.max - entry.op),
    jacket: null,   // 出图前换成本地 file:// 地址（attachAssets）
  };
}

// scores：落雪的全部成绩（玩家接口 /scores）；player：落雪的玩家资料（名片板、Rating、底色）
function buildData({ player, scores, catalog, now = new Date() }) {
  const result = analyze({ catalog, scores, player });
  const { possession } = result;
  const unplayed = result.headroom.unplayed;
  return {
    player: playerView(player),
    total: groupView(result.total),
    genres: result.genres.map((group) => ({ name: group.name, ...groupView(group) })),
    versions: result.versions.map((group) => ({ version: group.version, name: group.name, ...groupView(group) })),
    levels: LEVELS.map((level) => result.levels.find((group) => group.level === level)).filter(Boolean)
      .map((group) => ({ level: group.level, ...groupView(group) })),
    possession: {
      current: possession.current,
      currentName: POSSESSION_NAMES[possession.current] || POSSESSION_NAMES.normal,
      rating: possession.rating,
      ratingNeeded: possession.ratingNeeded,
      charts: possession.charts,
      percent: result.total.percent,
      next: possession.next ? possession.next.key : null,
      tiers: possession.tiers.map((tier) => ({
        key: tier.key, name: POSSESSION_NAMES[tier.key], rank: RANK_LABELS[tier.rank], below: tier.below, percent: tier.percent, done: tier.done,
      })),
    },
    headroom: {
      unplayed: { count: unplayed.length, max: round2(unplayed.reduce((sum, entry) => sum + entry.max, 0)), songs: unplayed.slice(0, HEADROOM).map((entry) => songView(entry, catalog)) },
      played: { count: result.headroom.played.length, songs: result.headroom.played.slice(0, HEADROOM).map((entry) => songView(entry, catalog)) },
    },
    note: NOTE,
    credit: "Generated by Anna Bot · 数据来自落雪查分器 · " + stamp(now),
  };
}

// 曲绘、名牌版、角色换成本地 file:// 地址。落雪素材很慢，只在出图队列里调
async function attachAssets(data, assets) {
  const items = [];
  const targets = [];
  const add = (kind, id, set) => { items.push([kind, id]); targets.push(set); };
  for (const song of [...data.headroom.unplayed.songs, ...data.headroom.played.songs]) add("jacket", song.jacketId, (url) => { song.jacket = url; });
  if (data.player.plateId !== null) add("plate", data.player.plateId, (url) => { data.player.plate = url; });
  if (data.player.characterId !== null) add("character", data.player.characterId, (url) => { data.player.character = url; });
  const urls = await assets.fileUrls(items);
  urls.forEach((url, i) => targets[i](url));
  return data;
}

module.exports = Object.assign({
  name: "over-power",
  words: ["OP进度", "op", "overpower"],
  usage: "/OP进度",
  summary: "全曲 OVER POWER 按分类、版本、等级拆开的进度，还有金底、蓝底的条件和推荐游玩的谱面。要授权。",
  panel: "OVER POWER 进度",
  group: "查询",
  binding: "oauth",
  async run(ctx) {
    const voice = ctx.voice;
    if (String(ctx.args || "").trim()) return ctx.reply(voice.overPowerUsage);
    await ctx.image({
      kind: "over-power",
      label: "OP 进度",
      render: async () => {
        const { catalog, assets, renderer } = ctx.services;
        // 玩家资料跟成绩一起取：名片板、总 Rating、底色都在资料里
        const [scores, player] = await Promise.all([ctx.player.scores(), ctx.player.player()]);
        const data = buildData({ player, scores, catalog, now: ctx.now ? ctx.now() : new Date() });
        await attachAssets(data, assets);
        const image = await renderer.render("over-power", data, {
          width: 2700, height: 1780, format: "jpeg", quality: 76, scale: RENDER_SCALE,
          maxBytes: 5_000_000, fallbackQualities: [68, 60, 52],
        });
        return { buffer: image.buffer };
      },
    });
  },
}, { buildData, attachAssets, songView, RENDER_SCALE, LEVELS, HEADROOM, NOTE });
